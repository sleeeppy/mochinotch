    static func text(_ key: Key, _ language: AppLanguage, _ args: CVarArg...) -> String {
        render(key, language, args)
    }

    /// `AppModel.text`가 이미 받은 인자를 다시 넘길 때. 가변 인자는 배열로 한 번 더 풀리지 않는다.
    static func render(_ key: Key, _ language: AppLanguage, _ args: [CVarArg]) -> String {
        let pattern = table[language]?[key] ?? table[.ko]?[key] ?? key.rawValue
        guard !args.isEmpty else { return pattern }
        return String(format: pattern, locale: language.locale, arguments: args)
    }

