/// 앱 안에서 고르는 언어. 맥 언어와 따로 저장하고, 바꾸면 노치 문구가 바로 바뀐다.
enum AppLanguage: String, CaseIterable, Identifiable {
    case ko
    case ja
    case en
    case zh

    var id: String { rawValue }

    /// 드롭다운에 보이는 이름. 지금 언어와 상관없이 자기 글로 보여야 고를 수 있다.
    var nativeName: String {
        switch self {
        case .ko: "한국어"
        case .ja: "日本語"
        case .en: "English"
        case .zh: "中文"
        }
    }

    var locale: Locale {
        switch self {
        case .ko: Locale(identifier: "ko")
        case .ja: Locale(identifier: "ja")
        case .en: Locale(identifier: "en")
        case .zh: Locale(identifier: "zh-Hans")
        }
    }

    /// 사용방법이 여는 안내 페이지.
    var guideURL: URL {
        let page: String
        switch self {
        case .ko: page = "https://github.com/sleeeppy/mochinotch#readme"
        case .ja: page = "https://github.com/sleeeppy/mochinotch/blob/main/docs/README.ja.md"
        case .en: page = "https://github.com/sleeeppy/mochinotch/blob/main/docs/README.en.md"
        case .zh: page = "https://github.com/sleeeppy/mochinotch/blob/main/docs/README.zh.md"
        }
        return URL(string: page)!
    }

    static let storageKey = "appLanguage"

    static var stored: AppLanguage {
        guard let raw = UserDefaults.standard.string(forKey: storageKey),
              let language = AppLanguage(rawValue: raw) else { return .ko }
        return language
    }
}

